#!/bin/bash
set -e

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"

# Colors for output
RED='\033[0;31m'
GREEN='\033[0;32m'
YELLOW='\033[1;33m'
NC='\033[0m' # No Color

info() { echo -e "${GREEN}[INFO]${NC} $1"; }
warn() { echo -e "${YELLOW}[WARN]${NC} $1"; }
error() { echo -e "${RED}[ERROR]${NC} $1"; exit 1; }

# Default values
DEFAULT_DOMAIN="example.com"
DEFAULT_DATA_DIR="/opt/stack"

# Management subnet default for UISP/Unifi GUI (empty means "no restriction")
DEFAULT_MGMT_SUBNET=""

# =========================
# Custom project management
# =========================

PROJECTS_FILE="$SCRIPT_DIR/.custom_projects"
OVERRIDE_FILE="$SCRIPT_DIR/compose.override.yml"

# Read a scalar value from a simple key: value YAML file
yaml_get() {
    local file="$1" key="$2"
    grep "^${key}:" "$file" 2>/dev/null | sed "s/^${key}: *//" | tr -d '\r'
}

# Regenerate compose.override.yml from .custom_projects
generate_override() {
    if [[ ! -f "$PROJECTS_FILE" ]] || [[ ! -s "$PROJECTS_FILE" ]]; then
        [[ -f "$OVERRIDE_FILE" ]] && rm "$OVERRIDE_FILE"
        info "No custom projects registered; compose.override.yml removed"
        return
    fi

    local caddy_nets="" net_defs="" includes=""

    while IFS= read -r proj || [[ -n "$proj" ]]; do
        [[ -z "$proj" ]] && continue
        local rel="${proj#./}"
        local manifest="$SCRIPT_DIR/$rel/homelab.yml"

        if [[ ! -f "$manifest" ]]; then
            warn "Missing homelab.yml in $proj — skipping"
            continue
        fi

        local net; net=$(yaml_get "$manifest" "backend_network")
        local cfile; cfile=$(yaml_get "$manifest" "compose")

        if [[ -n "$net" ]]; then
            caddy_nets+="      - ${net}"$'\n'
            net_defs+="  ${net}:"$'\n'
            net_defs+="    driver: bridge"$'\n'
            net_defs+="    external: false"$'\n'
            net_defs+="    internal: true"$'\n'
            net_defs+="    name: ${net}"$'\n'
        fi
        [[ -n "$cfile" ]] && includes+="  - path: ${proj}/${cfile}"$'\n'
    done < "$PROJECTS_FILE"

    {
        printf '# Auto-generated by setup.sh. Do not edit manually.\n'
        printf '# To manage custom projects: ./setup.sh --add-project <path>\n'
        printf '\n'

        if [[ -n "$caddy_nets" ]]; then
            printf 'services:\n'
            printf '  caddy:\n'
            printf '    networks:\n'
            printf '%s' "$caddy_nets"
            printf '\n'
            printf 'networks:\n'
            printf '%s' "$net_defs"
            printf '\n'
        fi

        if [[ -n "$includes" ]]; then
            printf 'include:\n'
            printf '%s' "$includes"
        fi
    } > "$OVERRIDE_FILE"

    info "Generated compose.override.yml"
}

# Copy caddy snippets for all registered projects into DATA_DIR/caddy/conf.d/
deploy_caddy_snippets() {
    local data_dir="$1"
    [[ -z "$data_dir" ]] && return
    [[ -f "$PROJECTS_FILE" ]] || return

    sudo mkdir -p "$data_dir/caddy/conf.d"

    while IFS= read -r proj || [[ -n "$proj" ]]; do
        [[ -z "$proj" ]] && continue
        local rel="${proj#./}"
        local manifest="$SCRIPT_DIR/$rel/homelab.yml"
        [[ ! -f "$manifest" ]] && continue

        local name; name=$(yaml_get "$manifest" "name")
        local snippet; snippet=$(yaml_get "$manifest" "caddy_snippet")
        [[ -z "$snippet" ]] && continue

        local src="$SCRIPT_DIR/$rel/$snippet"
        if [[ ! -f "$src" ]]; then
            warn "Caddy snippet not found: $src"
            continue
        fi

        sudo install -m 0644 -o root -g root "$src" "$data_dir/caddy/conf.d/${name}.caddy"
        info "Installed caddy snippet: conf.d/${name}.caddy"
    done < "$PROJECTS_FILE"
}

cmd_add_project() {
    local proj_path="$1"
    [[ -z "$proj_path" ]] && error "--add-project requires a path argument"

    # Normalise to a ./relative path from SCRIPT_DIR
    local rel
    rel=$(realpath --relative-to="$SCRIPT_DIR" "$proj_path" 2>/dev/null) || rel="$proj_path"
    [[ "$rel" != ./* ]] && rel="./$rel"

    local manifest_rel="${rel#./}"
    local manifest="$SCRIPT_DIR/$manifest_rel/homelab.yml"
    [[ ! -f "$manifest" ]] && error "No homelab.yml found in $proj_path"

    # Guard against duplicates
    if [[ -f "$PROJECTS_FILE" ]] && grep -qxF "$rel" "$PROJECTS_FILE"; then
        warn "Project already registered: $rel"
    else
        echo "$rel" >> "$PROJECTS_FILE"
        info "Registered project: $rel"
    fi

    generate_override

    # Deploy caddy snippet if DATA_DIR is known
    local data_dir=""
    if [[ -f "$SCRIPT_DIR/.env" ]]; then
        data_dir=$(grep "^DATA_DIR=" "$SCRIPT_DIR/.env" | cut -d= -f2)
    fi
    if [[ -n "$data_dir" ]]; then
        deploy_caddy_snippets "$data_dir"
    else
        warn "No .env found — caddy snippet not deployed. Run ./setup.sh first, then re-run --add-project."
    fi

    local name; name=$(yaml_get "$manifest" "name")
    local subdomain; subdomain=$(yaml_get "$manifest" "subdomain")

    echo
    info "Project '$name' added."
    if [[ -n "$data_dir" && -n "$subdomain" ]]; then
        local domain=""
        domain=$(grep "^BASE_DOMAIN=" "$SCRIPT_DIR/.env" | cut -d= -f2)
        [[ -n "$domain" ]] && echo "  URL: https://${subdomain}.${domain}"
    fi
    echo "  Restart the stack to apply: docker compose up -d"
}

cmd_remove_project() {
    local proj_path="$1"
    [[ -z "$proj_path" ]] && error "--remove-project requires a path argument"

    local rel
    rel=$(realpath --relative-to="$SCRIPT_DIR" "$proj_path" 2>/dev/null) || rel="$proj_path"
    [[ "$rel" != ./* ]] && rel="./$rel"

    if [[ ! -f "$PROJECTS_FILE" ]] || ! grep -qxF "$rel" "$PROJECTS_FILE"; then
        warn "Project not registered: $rel"
        exit 0
    fi

    local tmp; tmp=$(mktemp)
    grep -vxF "$rel" "$PROJECTS_FILE" > "$tmp" && mv "$tmp" "$PROJECTS_FILE"
    info "Unregistered project: $rel"

    # Remove caddy snippet from DATA_DIR if possible
    local data_dir=""
    if [[ -f "$SCRIPT_DIR/.env" ]]; then
        data_dir=$(grep "^DATA_DIR=" "$SCRIPT_DIR/.env" | cut -d= -f2)
    fi
    if [[ -n "$data_dir" ]]; then
        local rel_inner="${rel#./}"
        local manifest="$SCRIPT_DIR/$rel_inner/homelab.yml"
        if [[ -f "$manifest" ]]; then
            local name; name=$(yaml_get "$manifest" "name")
            local snippet_dest="$data_dir/caddy/conf.d/${name}.caddy"
            if [[ -f "$snippet_dest" ]]; then
                sudo rm "$snippet_dest"
                info "Removed caddy snippet: conf.d/${name}.caddy"
            fi
        fi
    fi

    generate_override

    echo
    echo "Project removed. Restart the stack to apply: docker compose up -d"
}

cmd_list_projects() {
    if [[ ! -f "$PROJECTS_FILE" ]] || [[ ! -s "$PROJECTS_FILE" ]]; then
        echo "No custom projects registered."
        return
    fi
    echo "Registered custom projects:"
    while IFS= read -r proj || [[ -n "$proj" ]]; do
        [[ -z "$proj" ]] && continue
        local rel="${proj#./}"
        local manifest="$SCRIPT_DIR/$rel/homelab.yml"
        if [[ -f "$manifest" ]]; then
            local name; name=$(yaml_get "$manifest" "name")
            local subdomain; subdomain=$(yaml_get "$manifest" "subdomain")
            printf "  %-30s  name: %-20s  subdomain: %s\n" "$proj" "$name" "$subdomain"
        else
            echo "  $proj  (homelab.yml missing!)"
        fi
    done < "$PROJECTS_FILE"
}

