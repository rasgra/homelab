# Argument parsing
# =========================

usage() {
    cat <<EOF
Usage: $(basename "$0") [OPTION]

Run without options to perform initial stack setup (interactive),
including optional UFW firewall configuration.

Options:
  -a, --add-project <path>     Register a custom project and deploy its Caddy snippet
  -r, --remove-project <path>  Unregister a custom project and remove its Caddy snippet
  -l, --list-projects          List all registered custom projects
  -f, --setup-firewall         Configure UFW firewall rules (reads active profiles from .env)
  -h, --help                   Show this help message

Examples:
  ./setup.sh                        # Initial interactive setup (includes firewall)
  ./setup.sh -a ./my-project        # Add a custom project
  ./setup.sh -r ./my-project        # Remove a custom project
  ./setup.sh -l                     # List registered projects
  ./setup.sh -f                     # (Re-)configure UFW firewall
EOF
}

cmd_setup_firewall() {
    if [[ ! -f "$SCRIPT_DIR/.env" ]]; then
        error "No .env found — run ./setup.sh first to create the initial configuration."
    fi
    PROFILES=$(grep "^COMPOSE_PROFILES=" "$SCRIPT_DIR/.env" | cut -d= -f2)
    if [[ -z "$PROFILES" ]]; then
        warn "COMPOSE_PROFILES not set in .env; only base rules (SSH, HTTP, HTTPS) will be applied."
    fi
    echo
    echo "========================================="
    echo "  UFW Firewall Setup"
    echo "========================================="
    echo
    setup_firewall
    echo
    echo "========================================="
    echo -e "${GREEN}  Firewall setup complete!${NC}"
    echo "========================================="
}

